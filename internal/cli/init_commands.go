package cli

import (
	"os"
	"path/filepath"
	"strings"
)

// Managed files carry this marker; a user who removes it owns the file and
// gx init will never overwrite it again.
const slashCommandMarker = "<!-- generated by gx init; remove this line to keep local edits -->"

// slashCommand is one command gx init installs into every detected agent. Each
// command carries its own content in the two body dialects the agents speak,
// and its own legacy names: files this tool installed under earlier names are
// removed on the next init so a rename leaves one command rather than two, and
// only when the file still carries a marker this tool wrote — a file the user
// has taken ownership of is theirs to delete.
type slashCommand struct {
	name         string // slash name and file base name, e.g. "gx" -> gx.md
	description  string // Claude Code frontmatter description
	argumentHint string // Claude Code frontmatter argument-hint
	bodyArgs     string // body for agents that substitute $ARGUMENTS (Claude Code, Codex)
	bodyPlain    string // body for Cursor, which appends the user's text instead
	legacyNames  []string
}

func slashCommands() []slashCommand {
	return []slashCommand{
		{
			name:         "gx",
			description:  "gx AI review of the current change",
			argumentHint: "[optional reviewer prompt]",
			bodyArgs:     slashGxBodyArgs,
			bodyPlain:    slashGxBodyPlain,
			legacyNames:  []string{"better-review"},
		},
		{
			name:         "constraints",
			description:  "gx pre-ship constraints exit gate for the current change",
			argumentHint: "[optional focus or intent hint]",
			bodyArgs:     slashConstraintsBodyArgs,
			bodyPlain:    slashConstraintsBodyPlain,
		},
	}
}

