// slashCommandAgent is one coding agent gx can install commands into: where
// its command files live under $HOME, and how a command renders for it.
type slashCommandAgent struct {
	name    string   // display name, e.g. "Claude Code"
	gateDir string   // directory under $HOME whose presence means the agent is installed
	dir     []string // command directory under $HOME
	render  func(slashCommand) string
}

func slashCommandAgents() []slashCommandAgent {
	return []slashCommandAgent{
		{
			name:    "Claude Code",
			gateDir: ".claude",
			dir:     []string{".claude", "commands"},
			render:  renderClaudeSlashCommand,
		},
		{
			name:    "Cursor",
			gateDir: ".cursor",
			dir:     []string{".cursor", "commands"},
			render:  func(cmd slashCommand) string { return cmd.bodyPlain },
		},
		{
			name:    "Codex",
			gateDir: ".codex",
			dir:     []string{".codex", "prompts"},
			render:  func(cmd slashCommand) string { return cmd.bodyArgs },
		},
	}
}

func renderClaudeSlashCommand(cmd slashCommand) string {
	return "---\ndescription: " + cmd.description + "\nargument-hint: " + cmd.argumentHint + "\n---\n\n" + cmd.bodyArgs
}

// installSlashCommands writes the user-level command files for each agent
// whose config directory exists, skipping files the user has taken ownership
// of and removing files left behind under earlier command names. It returns
// the display names of agents with at least one managed command file in place
// after the call — with several commands per agent, per-command precision
// would say more than the one init output line can show, and write errors are
// already swallowed file by file in the same spirit.
func installSlashCommands() ([]string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return nil, err
	}
	var installed []string
	for _, agent := range slashCommandAgents() {
		if info, statErr := os.Stat(filepath.Join(home, agent.gateDir)); statErr != nil || !info.IsDir() {
			continue
		}
		inPlace := false
		for _, cmd := range slashCommands() {
			removeLegacySlashCommands(home, agent, cmd)
			path := filepath.Join(append(append([]string{home}, agent.dir...), cmd.name+".md")...)
			content := agent.render(cmd)
			if data, readErr := os.ReadFile(path); readErr == nil {
				if !isManagedSlashCommand(string(data)) {
					// User-owned; leave this file alone, keep installing the rest.
					continue
				}
				if string(data) == content {
					inPlace = true
					continue
				}
			}
			if mkErr := os.MkdirAll(filepath.Dir(path), 0o755); mkErr != nil {
				continue
			}
			if writeErr := os.WriteFile(path, []byte(content), 0o644); writeErr != nil {
				continue
			}
			inPlace = true
		}
		if inPlace {
			installed = append(installed, agent.name)
		}
	}
	return installed, nil
}

// isManagedSlashCommand reports whether this tool wrote the file.
func isManagedSlashCommand(content string) bool {
	return strings.Contains(content, slashCommandMarker)
}

// removeLegacySlashCommands deletes command files this tool installed under a
// previous name, leaving anything the user has edited in place. A legacy name
// that collides with any CURRENT command's name is never deleted: all commands
// share one directory per agent, so deleting it would delete a live command.
func removeLegacySlashCommands(home string, agent slashCommandAgent, cmd slashCommand) {
	for _, legacy := range cmd.legacyNames {
		if slashCommandNameInUse(legacy) {
			continue
		}
		path := filepath.Join(append(append([]string{home}, agent.dir...), legacy+".md")...)
		data, err := os.ReadFile(path)
		if err != nil || !isManagedSlashCommand(string(data)) {
			continue
		}
		_ = os.Remove(path)
	}
}

func slashCommandNameInUse(name string) bool {
	for _, cmd := range slashCommands() {
		if cmd.name == name {
			return true
		}
	}
	return false
}
